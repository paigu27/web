package com.myblog.model;

/**
 * Week 03 - MyBlog 的完整身份（PersonalProfile）。
 * 每个字段对应身份四问之一：
 *   blogName     —— 这个博客归谁所有（名字）
 *   owner        —— 这个博客归谁所有（人）
 *   introduction —— 我如何自我介绍
 *   interests    —— 我在乎什么
 *   vision       —— 我正在成为什么样的人
 */
public class PersonalProfile {
    public String blogName;
    public String owner;
    public String introduction;
    public String interests;
    public String vision;
}
